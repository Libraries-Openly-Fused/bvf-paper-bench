#!/usr/bin/env python3
"""Tables of the NPPDx resize-range sweep, from the output directory of sweep.py.

    nppdx-resize-range/report.py <sweep output directory> <tables.md>
"""

import csv
import sys
from collections import Counter, defaultdict
from fractions import Fraction
from pathlib import Path

METHODS = ["nearest", "bilinear", "bicubic", "lanczos3"]
LEVEL_TEXT = {
    "compiles": "compiles",
    "compiles_j_divides": "compiles, J divides the tile",
    "fits_smem": "fits the shared memory",
    "fits_smem_j_divides": "fits the shared memory, J divides the tile",
    "fits_smem_example_block": "fits the shared memory and the example's block",
    "fits_smem_example_block_j_divides": "fits the shared memory and the example's block, J divides the tile",
}


def read_csv(path):
    with open(path, newline="") as f:
        return list(csv.DictReader(f))


def factor(j, k):
    f = Fraction(int(k), int(j))
    return float(f if f >= 1 else 1 / f)


def launch_text(row):
    """What the launch on the RTX 4090 did, for an SM 890 point."""
    if row["compiled"] != "yes":
        return "not compiled"
    result = row["launch_result"]
    if result == "ran":
        interior = row["launch_max_diff_interior"]
        over = row["launch_interior_values_over_1"]
        text = f"ran, interior max diff {interior}"
        if over not in ("", "0"):
            text += f" ({over} values > 1)"
        r32 = row["launch32_result"]
        if r32 == "ran" and row["launch32_max_diff_interior"] != interior:
            text += f"; 32 threads: {row['launch32_max_diff_interior']}"
        elif r32 and r32 != "ran":
            text += f"; 32 threads: {r32}"
        return text
    if result:
        return f"{result} ({row['launch_error']})"
    return ""


def main():
    if len(sys.argv) != 3:
        print(__doc__)
        return 1
    d = Path(sys.argv[1])
    out = Path(sys.argv[2])
    sweep = read_csv(d / "sweep.csv")
    summary = read_csv(d / "rules" / "rules_summary.csv")
    by_key = {(r["sm"], r["method"], r["J"], r["K"], r["tile"]): r for r in sweep}
    lines = []
    w = lines.append

    w("# NPPDx resize range: tables")
    w("")
    w(f"Generated by `report.py` from `{d}`.")
    env = (d / "environment.txt").read_text().strip().splitlines()
    w("")
    for e in env:
        w(f"- {e}")
    w("")

    # ---------------------------------------------------------------------------------------------------------------
    w("## Largest factors (NPPDx's rules over every coprime J:K up to "
      f"{summary[0]['max_J_and_K_searched']} and every tile)")
    w("")
    w("Factor K/J for an upscale, J/K for a downscale; the tile with the least shared memory at that ratio; the "
      "shared memory of the whole pipeline (four tiles of 3 float channels). Compiled and launched: the same point "
      "with resize_probe.cu (SM 890 points launched on the RTX 4090; interior max diff in 8-bit levels against the "
      "CPU reference).")
    for sm in ("890", "900"):
        limit = next(r["shared_memory_limit"] for r in summary if r["sm"] == sm)
        w("")
        w(f"### SM {sm} (shared memory limit {limit} bytes"
          f"{', cudaDevAttrMaxSharedMemoryPerBlockOptin of the RTX 4090' if sm == '890' else ', NPPDx table'})")
        w("")
        w("| method | direction | level | factor | J:K | tile | output tile | smem bytes | block | compiled | launch |")
        w("|---|---|---|---|---|---|---|---|---|---|---|")
        for direction in ("upscale", "downscale"):
            for method in METHODS:
                for r in summary:
                    if r["sm"] != sm or r["method"] != method or r["direction"] != direction:
                        continue
                    s = by_key.get((sm, method, r["J"], r["K"], r["tile"]))
                    compiled = s["compiled"] if s else "not swept"
                    launch = launch_text(s) if s and sm == "890" else ""
                    w(f"| {method} | {direction} | {LEVEL_TEXT[r['level']]} | {float(r['max_factor']):.3f} | "
                      f"{r['J']}:{r['K']} | {r['tile']} | {r['output_storage']} | {r['smem_bytes']} | {r['block']} | "
                      f"{compiled} | {launch} |")
        w("")
        w("The next integer factor at the same tile (J:1 + 1 or 1:K + 1), compiled:")
        w("")
        w("| method | point | why | compiled | static_assert | smem bytes | launch |")
        w("|---|---|---|---|---|---|---|")
        for s in sweep:
            if s["sm"] != sm or "next:" not in s["why"]:
                continue
            whys = sorted({x.split(":", 1)[1] for x in s["why"].split() if x.startswith("next:")})
            w(f"| {s['method']} | {s['J']}:{s['K']} {s['tile']} | next after {', '.join(whys)} | {s['compiled']} | "
              f"{s['static_asserts']} | {s['smem_bytes']} | {launch_text(s) if sm == '890' else ''} |")

    # ---------------------------------------------------------------------------------------------------------------
    w("")
    w("## Which ratios have a correct configuration (NPPDx's rules, every coprime J:K up to "
      f"{summary[0]['max_J_and_K_searched']})")
    w("")
    w("A ratio has one if some tile compiles, fits the shared memory with the example's block and has J dividing it.")
    w("")
    w("| SM | method | ratios | largest J | largest K | closest to 1 (upscale) | closest to 1 (downscale) |")
    w("|---|---|---|---|---|---|---|")
    level = "fits_smem_example_block_j_divides"
    feasible = defaultdict(set)
    # Next to tables.md: every ratio that has one, with its best tile (rules_by_ratio.csv is too big to keep)
    with open(d / "rules" / "rules_by_ratio.csv", newline="") as f, \
            open(out.parent / "feasible_ratios.csv", "w", newline="") as g:
        writer = csv.writer(g)
        writer.writerow(["sm", "method", "J", "K", "factor", "direction", "tiles", "best_tile", "smem_bytes",
                         "output_tile", "block"])
        for r in csv.DictReader(f):
            if r[f"{level}_best_tile"]:
                j, k = int(r["J"]), int(r["K"])
                feasible[(r["sm"], r["method"])].add((j, k))
                writer.writerow([r["sm"], r["method"], j, k, f"{factor(j, k):.4f}",
                                 "upscale" if k > j else ("downscale" if j > k else "identity"),
                                 r[f"{level}_tiles"], r[f"{level}_best_tile"], r[f"{level}_best_smem"],
                                 r[f"{level}_best_output"], r[f"{level}_best_block"]])
    for sm in ("890", "900"):
        for method in METHODS:
            s = feasible[(sm, method)]
            up = min((jk for jk in s if jk[1] > jk[0]), key=lambda jk: Fraction(jk[1], jk[0]))
            down = min((jk for jk in s if jk[0] > jk[1]), key=lambda jk: Fraction(jk[0], jk[1]))
            w(f"| {sm} | {method} | {len(s)} | {max(j for j, _ in s)} | {max(k for _, k in s)} | {up[0]}:{up[1]} | "
              f"{down[0]}:{down[1]} |")

    # ---------------------------------------------------------------------------------------------------------------
    w("")
    w("## The compiled points")
    w("")
    agreement = (d / "agreement.txt").read_text().strip().splitlines()
    for a in agreement[:3]:
        w(f"- {a}")
    w("")
    w("| SM | points | compiled | rejected | timeouts | other errors |")
    w("|---|---|---|---|---|---|")
    for sm in ("890", "900"):
        rows = [s for s in sweep if s["sm"] == sm]
        c = Counter(s["compiled"] for s in rows)
        other = sum(1 for s in rows if s["compiled"] == "no" and not s["static_asserts"])
        w(f"| {sm} | {len(rows)} | {c['yes']} | {c['no']} | {c['timeout']} | {other} |")
    w("")
    w("Static assertions of the rejected points (a point can fail several):")
    w("")
    w("| static_assert | points | rules' failing checks of those points |")
    w("|---|---|---|")
    texts = Counter()
    checks = defaultdict(Counter)
    for s in sweep:
        if s["compiled"] == "no":
            for t in s["static_asserts"].split(" | "):
                if t:
                    texts[t] += 1
                    checks[t][s["predicted_failing_checks"]] += 1
    for t, n in texts.most_common():
        w(f"| {t} | {n} | {', '.join(f'{k} ({v})' for k, v in checks[t].most_common())} |")
    others = [s for s in sweep if s["compiled"] == "no" and not s["static_asserts"]]
    if others:
        w("")
        w("Rejected without a static_assert:")
        for s in others[:20]:
            w(f"- SM {s['sm']} {s['method']} {s['J']}:{s['K']} {s['tile']}: {s['other_errors']}")

    # ---------------------------------------------------------------------------------------------------------------
    w("")
    w("## Launches on the RTX 4090 (every SM 890 point that compiled)")
    w("")
    w("| J divides the tile | launch | points | interior max diff <= 1 | interior max diff > 1 | no interior pixel |")
    w("|---|---|---|---|---|---|")
    groups = defaultdict(list)
    for s in sweep:
        if s["sm"] == "890" and s["compiled"] == "yes":
            groups[(s["j_divides_tile"], s["launch_result"] + (f" ({s['launch_error']})" if s["launch_error"] else ""))
                   ].append(s)
    for (div, res), rows in sorted(groups.items()):
        ok = bad = none = 0
        if res == "ran":
            for s in rows:
                if s["launch_max_diff_interior"] == "" or s["launch_interior_pixels"] == "0":
                    none += 1
                elif int(s["launch_max_diff_interior"]) <= 1:
                    ok += 1
                else:
                    bad += 1
        w(f"| {div} | {res} | {len(rows)} | {ok if res == 'ran' else ''} | {bad if res == 'ran' else ''} | "
          f"{none if res == 'ran' else ''} |")
    w("")
    w("With 32 threads per block instead of the example's one thread per cell:")
    w("")
    c32 = Counter()
    for s in sweep:
        if s["sm"] == "890" and s["launch_result"] == "ran":
            same = s["launch32_result"] == "ran" and s["launch32_max_diff_interior"] == s["launch_max_diff_interior"] \
                and s["launch32_max_diff"] == s["launch_max_diff"]
            c32["same errors as the example's block" if same else f"different: {s['launch32_result']}"] += 1
    for k, v in c32.most_common():
        w(f"- {k}: {v} points")

    # ---------------------------------------------------------------------------------------------------------------
    w("")
    w("## Ratios of the sweep")
    w("")
    w("Per ratio and method: how many tiles of the tile grid compile (SM 890), and the tile with the least shared memory "
      "that compiles, fits the RTX 4090 with the example's block and has J dividing it (NPPDx's rules over every "
      "tile), with what it did on the GPU; then the same tile choice for SM 900 (compiled only).")
    w("")
    w("| J:K | factor | method | grid tiles compiled (SM 890) | SM 890 tile | output tile | smem bytes | launch | "
      "SM 900 tile | smem bytes | compiled |")
    w("|---|---|---|---|---|---|---|---|---|---|---|")
    grid = defaultdict(lambda: [0, 0])
    best = {}
    for s in sweep:
        key = (s["J"], s["K"], s["method"])
        if "grid" in s["why"].split() and s["sm"] == "890":
            grid[key][1] += 1
            grid[key][0] += s["compiled"] == "yes"
        if "best:fits_smem_example_block_j_divides" in s["why"].split():
            best[(s["sm"],) + key] = s
    ratios = sorted({(s["J"], s["K"]) for s in sweep if "grid" in s["why"].split()},
                    key=lambda jk: (int(jk[1]) <= int(jk[0]), factor(*jk)))
    for j, k in ratios:
        for method in METHODS:
            key = (j, k, method)
            g = grid[key]
            b8 = best.get(("890",) + key)
            b9 = best.get(("900",) + key)
            c8 = (f"{b8['tile']} | {b8['output_storage']} | {b8['smem_bytes']} | {launch_text(b8)}" if b8
                  else "none | | | ")
            c9 = f"{b9['tile']} | {b9['smem_bytes']} | {b9['compiled']}" if b9 else "none | | "
            w(f"| {j}:{k} | {factor(j, k):.3f} | {method} | {g[0]}/{g[1]} | {c8} | {c9} |")

    out.write_text("\n".join(lines) + "\n")
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
