#!/usr/bin/env python3
"""Tables of the full-protocol W2 runs of nppdx-wins (benchmark_wins_frame*), from their output directories.

    nppdx-wins/full_report.py <results directory> <tables.md>

The results directory holds one output directory per case (k5, k5_p2, k9, gauss21), each with the main run and the
L2-flushed run of the harness (per_iteration_latency.csv, per_iteration_gpu_only.csv,
per_iteration_gpu_only_l2_flushed.csv, kernels.csv, validation.csv, choices.csv, choice_sweep.csv, platform.txt).
For every case and mode: the median and p10-p90 of every implementation, and the per-iteration mean speedups in both
directions, nppdx over each FKL form (mean of t_fkl / t_nppdx over the iterations) and each FKL form over nppdx (mean of
t_nppdx / t_fkl).
"""

import csv
import sys
from collections import defaultdict
from pathlib import Path

CASES = [("k5", "box 5x5, one pass"), ("k5_p2", "box 5x5, two passes"), ("k9", "box 9x9"),
         ("gauss21", "Gaussian, 21 taps (NPPDx GaussianBlur<50, wide>, sigma 5)")]
MODES = [("latency", "latency (CPU + GPU)"), ("gpu_only", "GPU only"),
         ("gpu_only_l2_flushed", "GPU only, L2 flushed")]
ORDER = ["nppdx", "fkl_inline", "fkl_staged", "fkl_staged_separable"]


def read_csv(path):
    with open(path, newline="") as f:
        return list(csv.DictReader(f))


def percentile(sorted_values, q):
    """Linear interpolation between closest ranks, as numpy's default"""
    if not sorted_values:
        return float("nan")
    pos = (len(sorted_values) - 1) * q
    lo = int(pos)
    hi = min(lo + 1, len(sorted_values) - 1)
    return sorted_values[lo] + (sorted_values[hi] - sorted_values[lo]) * (pos - lo)


def per_iteration(path):
    """{implementation: {iteration: us}}"""
    times = defaultdict(dict)
    for r in read_csv(path):
        times[r["implementation"]][int(r["iteration"])] = float(r["us"])
    return times


def main():
    if len(sys.argv) != 3:
        print(__doc__)
        return 1
    root = Path(sys.argv[1])
    out = Path(sys.argv[2])
    lines = []
    w = lines.append
    key = []
    w("# nppdx-wins W2, full protocol: tables")
    w("")
    w(f"Generated by `full_report.py` from `{root.name}`. Medians and p10-p90 in us; speedups are per-iteration means.")
    for case, label in CASES:
        d = root / case
        if not d.exists():
            continue
        platform = (d / "platform.txt").read_text().splitlines()
        commit = next((l for l in platform if l.startswith("bvf-paper-bench: commit")), "")
        fkl = next((l for l in platform if l.startswith("FKL:")), "")
        w("")
        w(f"## {label} (`{case}`)")
        w("")
        w(f"- {commit}; {fkl}")
        kernels = {r["implementation"]: r["kernels"] for r in read_csv(d / "kernels.csv")}
        choices = read_csv(d / "choices.csv")
        sweep = read_csv(d / "choice_sweep.csv") if (d / "choice_sweep.csv").exists() else []
        for c in choices:
            cands = [s for s in sweep if s["key"] == c["key"] and s["chosen"] == "yes"]
            how = c.get("how", "swept")
            w(f"- configuration {c['key']}: {cands[0]['candidate'] if cands else 'candidate ' + c['index']} ({how})")
        # Validation over the validated iterations
        validation = defaultdict(list)
        for r in read_csv(d / "validation.csv"):
            validation[r["implementation"]].append(r)
        w("")
        w("| implementation | kernels | validated iterations | max abs error (own reference) | within tolerance |")
        w("|---|---|---|---|---|")
        impls = [i for i in ORDER if i in kernels]
        for impl in impls:
            rows = validation[impl]
            err = max(float(max(r["max_abs_err_r"], r["max_abs_err_g"], r["max_abs_err_b"], key=float)) for r in rows)
            ok = all(r["within_tolerance"] == "yes" for r in rows)
            w(f"| {impl} | {kernels[impl]} | {len(rows)} ({rows[0]['reference']}) | {err:.3e} | "
              f"{'yes' if ok else 'NO'} |")
        for mode, mode_label in MODES:
            path = d / f"per_iteration_{mode}.csv"
            if not path.exists():
                continue
            times = per_iteration(path)
            iterations = sorted(times["nppdx"])
            w("")
            w(f"### {mode_label} ({len(iterations)} timed iterations)")
            w("")
            w("| implementation | median | p10 | p90 | nppdx's mean speedup over it | its mean speedup over nppdx |")
            w("|---|---|---|---|---|---|")
            stats = {}
            for impl in impls:
                values = sorted(times[impl][i] for i in iterations)
                stats[impl] = (percentile(values, 0.5), percentile(values, 0.1), percentile(values, 0.9))
                if impl == "nppdx":
                    w(f"| nppdx | {stats[impl][0]:.2f} | {stats[impl][1]:.2f} | {stats[impl][2]:.2f} | | |")
                    continue
                nppdx_over = sum(times[impl][i] / times["nppdx"][i] for i in iterations) / len(iterations)
                over_nppdx = sum(times["nppdx"][i] / times[impl][i] for i in iterations) / len(iterations)
                w(f"| {impl} | {stats[impl][0]:.2f} | {stats[impl][1]:.2f} | {stats[impl][2]:.2f} | "
                  f"{nppdx_over:.3f} | {over_nppdx:.3f} |")
                key.append(f"{case},{mode},{impl},{stats[impl][0]:.2f},{stats[impl][1]:.2f},{stats[impl][2]:.2f},"
                           f"{nppdx_over:.4f},{over_nppdx:.4f}")
            key.append(f"{case},{mode},nppdx,{stats['nppdx'][0]:.2f},{stats['nppdx'][1]:.2f},{stats['nppdx'][2]:.2f},,")
            fastest = min(stats, key=lambda i: stats[i][0])
            fkl_forms = [i for i in impls if i != "nppdx" and i != "fkl_staged_separable"]
            faster_fkl = min(fkl_forms, key=lambda i: stats[i][0])
            w("")
            w(f"Fastest median: **{fastest}**. Faster of the two FKL forms: {faster_fkl}."
              + (" (fkl_staged_separable is an extra, not one of the two forms.)" if "fkl_staged_separable" in impls
                 else ""))
    out.write_text("\n".join(lines) + "\n")
    (out.parent / "key_numbers.csv").write_text(
        "case,mode,implementation,median_us,p10_us,p90_us,nppdx_mean_speedup_over_it,its_mean_speedup_over_nppdx\n"
        + "\n".join(key) + "\n")
    print(f"wrote {out} and {out.parent / 'key_numbers.csv'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
